#!/usr/bin/env node
/**
 * validate-content-drift.mjs — canonical-facts content-drift gate.
 * Pure Node ESM, zero dependencies.
 *
 * Enforces docs/CANONICAL_FACTS.md: scans the scannable content surface for
 * forbidden patterns (stale founding year, blue-fire "guarantee" wording,
 * stale review counts, non-IDR prices, stale deposit/group terms, unverified
 * press names, and the retired root jvto-config.json brand-config JSON
 * pattern). Every hit prints `file:line — rule-name — matched text`.
 *
 * Scope (scanned):
 *   - src/            (recursive)
 *   - public/llms*.txt
 *   - docs/CANONICAL_FACTS.md
 *   - repo-root *-config.json files (structural guard against a second
 *     brand-config file recurring, per CONTRIBUTING.md §5 / jvto-config.json)
 *
 * Excluded (by design):
 *   - src/lib/publicContent/generated/  (DB snapshots — never hand-edited;
 *     regenerated by scripts/export-*.mjs)
 *   - src/generated/                    (machine-generated Prisma client)
 *   - any path segment named "uploads" or "node_modules"
 *   - docs/design-reference/            (historical design dossier)
 *   - binary files (images/fonts/media) by extension
 *
 * Whitelist: any LINE containing the marker `drift-ok:` is skipped — used by
 * docs/CANONICAL_FACTS.md itself (and other deliberate anti-pattern-quoting
 * comments) to whitelist a specific line. A drift-ok marker must always carry
 * a reason after the colon.
 *
 * GATE MODE — same governance pattern as scripts/lint-gate.mjs: this repo had
 * ~48 pre-existing content-drift hits scattered across legacy/mock data files
 * the day this validator was introduced (2026-07-06) — files nobody had
 * scanned for these patterns before. Rather than either (a) hard-blocking
 * every future PR until all 48 are individually fixed, or (b) loosening the
 * regexes to stop noticing them, hits are gated against a COMMITTED
 * per-file/per-rule baseline (scripts/content-drift-baseline.json): any
 * bucket that grows beyond its baseline count = FAIL. Fixing a legacy hit
 * elsewhere never offsets a new one appearing somewhere else.
 *   - Fixed a legacy hit: `node scripts/validate-content-drift.mjs --update`
 *     regenerates the baseline; commit the (smaller) diff for review.
 *   - New code introducing NEW drift: gate fails naming the exact bucket(s)
 *     that grew, regardless of the total hit count elsewhere.
 *
 * Usage: node scripts/validate-content-drift.mjs [--update]  (no other args;
 * extra args are otherwise ignored so `npm run validate <sub>` arg-append
 * cannot break the chain)
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASELINE_PATH = path.join(ROOT, 'scripts', 'content-drift-baseline.json');

// ── rules (data, not code) ────────────────────────────────────────────────────
// Each hit of any rule on a non-whitelisted line fails the gate.

const RULES = [
  {
    name: 'stale-address-linebreak',
    re: /Banyuwangi, East Java,\s*<br/i,
  },
  {
    name: 'stale-review-counts',
    // canonical: Trustpilot 4.8/51 · Google 4.9/123 · TripAdvisor 4.95/21 · cross-platform 4.8/195
    // Bare 112/92 as review counts (e.g. `reviewCount: 112`, "112 reviews") are
    // forbidden values per the facts lock, not just the "112+" / compound forms.
    re: /\b112\+|4\.9\s*\/\s*5 · 92|47 reviews|5\.0\s*\/\s*5\b|reviewCount["'\s:=]*11[2]\b|reviewCount["'\s:=]*92\b|4\.9\s*\/\s*112\b|\b112\s*reviews?\b|\b92\s*reviews?\b/i,
  },
  {
    name: 'wrong-founding-year',
    // canonical foundingDate/since = 2015 (docs/CANONICAL_FACTS.md). 2023 is
    // legitimate for legal/PT-formalization context (e.g. "TDUP issued
    // 2023-02-11") but forbidden specifically as a foundingDate value — so
    // only that alternative gains |23, not "incorporated"/"EST".
    re: /incorporated 20(16|19|20)|EST\.? 20(16|19|20)|foundingDate["']?\s*[:=]\s*["']20(16|19|20|23)/i,
  },
  {
    name: 'brand-config-json-pattern',
    // retired root jvto-config.json duplicate brand-config shape — must never reappear
    re: /"sinceOperational"|"incorporated":\s*"?20\d\d/,
  },
  {
    name: 'mandatory-health-wording',
    // Ijen health screening is CONDITIONAL (BBKSDA SE.1658/KSA.9/2024), never "mandatory for all"
    re: /[Mm]andatory health|required for all\s+\w{0,8}guests|must hold a valid/,
  },
  {
    name: 'blue-fire-guarantee',
    // blue fire = natural phenomenon, cannot be guaranteed
    re: /[Bb]lue\s*[Ff]ire[^.]{0,40}(guarantee|100%)|guarantee[^.]{0,40}[Bb]lue\s*[Ff]ire/,
  },
  {
    name: 'non-idr-currency',
    // prices are IDR-only, format `IDR 1,550,000/person`
    re: /\$\s?\d|EUR\s?\d|USD\s?\d{2,}|Rp\s?\d/,
  },
  {
    name: 'stale-deposit-terms',
    // canonical: 20% deposit; cancellation = 100% Lifetime Travel Credit
    re: /30% deposit|balance[^.]{0,20}at pickup/i,
  },
  {
    name: 'stale-group-threshold',
    // police-escort threshold is ~18 guests, not 6
    re: /[Gg]roups of 6|6\+ (guests|travel)/,
  },
  {
    name: 'unverified-press-names',
    re: /Trip\.com|Travel \+ Leisure|Cond[eé] Nast/,
  },
];

const WHITELIST_MARKER = 'drift-ok:';

// ── scope ─────────────────────────────────────────────────────────────────────

const EXCLUDED_DIR_SEGMENTS = new Set(['node_modules', 'uploads']);
const EXCLUDED_PREFIXES = [
  path.join('src', 'lib', 'publicContent', 'generated') + path.sep,
  path.join('src', 'generated') + path.sep,
  path.join('docs', 'design-reference') + path.sep,
];

const BINARY_EXTENSIONS = new Set([
  '.png', '.jpg', '.jpeg', '.gif', '.webp', '.avif', '.ico', '.bmp', '.tiff',
  '.woff', '.woff2', '.ttf', '.otf', '.eot',
  '.pdf', '.zip', '.gz', '.tar', '.rar', '.7z',
  '.mp3', '.mp4', '.webm', '.wav', '.ogg', '.mov',
  '.node', '.wasm', '.so', '.dylib', '.dll', '.jar',
  '.psd', '.ai', '.sketch',
]);

function isExcluded(relPath) {
  if (EXCLUDED_PREFIXES.some((p) => relPath.startsWith(p))) return true;
  return relPath
    .split(path.sep)
    .some((seg) => EXCLUDED_DIR_SEGMENTS.has(seg));
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(ROOT, full);
    if (isExcluded(rel + (entry.isDirectory() ? path.sep : ''))) continue;
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

function collectTargets() {
  const targets = [];
  targets.push(...walk(path.join(ROOT, 'src')));
  // Root-level brand-config JSON files (the jvto-config.json pattern this
  // validator exists to prevent recurring — see CONTRIBUTING.md §5). Matches
  // "*-config.json" specifically (hyphen/underscore before "config") so it
  // never picks up unrelated root configs like tsconfig.json.
  for (const entry of readdirSync(ROOT, { withFileTypes: true })) {
    if (entry.isFile() && /[-_]config\.json$/i.test(entry.name)) {
      targets.push(path.join(ROOT, entry.name));
    }
  }
  const publicDir = path.join(ROOT, 'public');
  for (const entry of readdirSync(publicDir, { withFileTypes: true })) {
    if (entry.isFile() && /^llms.*\.txt$/.test(entry.name)) {
      targets.push(path.join(publicDir, entry.name));
    }
  }
  const factsLock = path.join(ROOT, 'docs', 'CANONICAL_FACTS.md');
  try {
    statSync(factsLock);
    targets.push(factsLock);
  } catch {
    console.error('✗ docs/CANONICAL_FACTS.md not found — facts lock missing');
    process.exitCode = 1;
  }
  return targets.filter((f) => !BINARY_EXTENSIONS.has(path.extname(f).toLowerCase()));
}

// ── scan ──────────────────────────────────────────────────────────────────────

function truncate(text, max = 80) {
  const oneLine = text.replace(/\s+/g, ' ').trim();
  return oneLine.length > max ? oneLine.slice(0, max - 1) + '…' : oneLine;
}

function scanFile(file) {
  let content;
  try {
    content = readFileSync(file, 'utf8');
  } catch {
    return []; // unreadable — out of scope
  }
  if (content.includes('\u0000')) return []; // binary despite extension
  const hits = [];
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.includes(WHITELIST_MARKER)) continue;
    for (const rule of RULES) {
      const m = rule.re.exec(line);
      if (m) hits.push({ rel, line: i + 1, rule: rule.name, text: truncate(m[0]) });
    }
  }
  return hits;
}

// ── entrypoint ────────────────────────────────────────────────────────────────

const targets = collectTargets();
const allHits = [];
for (const file of targets) allHits.push(...scanFile(file));

for (const h of allHits) console.log(`✗ ${h.rel}:${h.line} — ${h.rule} — ${h.text}`);
console.log(
  `\n[content-drift] ${targets.length} files scanned, ${RULES.length} rules — ${allHits.length} hit(s)`,
);

// Bucket by file+rule (line numbers excluded — they shift on unrelated edits
// and would false-positive constantly), same approach as scripts/lint-gate.mjs.
const current = {};
for (const h of allHits) {
  const key = `${h.rel} :: ${h.rule}`;
  current[key] = (current[key] ?? 0) + 1;
}

if (process.argv.includes('--update')) {
  const sorted = Object.fromEntries(Object.entries(current).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(BASELINE_PATH, JSON.stringify(sorted, null, 2) + '\n');
  console.log(`[content-drift] baseline written: ${allHits.length} hits across ${Object.keys(current).length} buckets → ${path.relative(ROOT, BASELINE_PATH)}`);
  process.exit(0);
}

let baseline;
try {
  baseline = JSON.parse(readFileSync(BASELINE_PATH, 'utf8'));
} catch {
  console.error(`[content-drift] missing/unreadable ${path.relative(ROOT, BASELINE_PATH)} — run \`node scripts/validate-content-drift.mjs --update\` on a clean checkout and commit it.`);
  process.exit(1);
}

const baseTotal = Object.values(baseline).reduce((s, n) => s + n, 0);
console.log(`[content-drift] baseline: ${baseTotal} hits in ${Object.keys(baseline).length} bucket(s)`);

const regressions = Object.entries(current)
  .filter(([key, count]) => count > (baseline[key] ?? 0))
  .map(([key, count]) => `  ${key} — ${count} hit(s), baseline ${baseline[key] ?? 0}`);

if (regressions.length) {
  console.log(`[content-drift] FAIL — new drift beyond baseline in ${regressions.length} bucket(s):`);
  for (const line of regressions) console.log(line);
  console.log(
    '[content-drift] Fix the new content per docs/CANONICAL_FACTS.md, or mark a line with',
  );
  console.log(
    "[content-drift] `drift-ok: <reason>` ONLY when it quotes a forbidden example deliberately.",
  );
  console.log(
    '[content-drift] Fixing a different, already-baselined hit does not offset a new one.',
  );
  process.exitCode = 1;
} else {
  if (allHits.length < baseTotal) {
    console.log(`[content-drift] NOTE: legacy hits were fixed (${baseTotal} → ${allHits.length}) — run \`node scripts/validate-content-drift.mjs --update\` and commit the baseline so they cannot return.`);
  }
  console.log('[content-drift] PASS');
}
