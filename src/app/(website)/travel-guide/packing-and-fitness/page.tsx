const renderTextWithLinks = (text: string) => {
    const parts = text.split(/(`\/travel-guide\/[a-z-]+`|\/travel-guide\/[a-z-]+)/g);
    return parts.map((part, index) => {
      const isLink = part.match(/^\/?travel-guide\/[a-z-]+$/);
      if (isLink) {
        return <Link key={index} href={part} className="text-primary hover:underline">{part}</Link>;
      }
      const isCodeLink = part.match(/^`(\/travel-guide\/[a-z-]+)`$/);
       if (isCodeLink) {
        return <Link key={index} href={isCodeLink[1]} className="text-primary hover:underline">{isCodeLink[1]}</Link>;
      }
      // Handle **bold** text
      const boldParts = part.split(/\*\*(.*?)\*\*/g);
      return boldParts.map((boldPart, boldIndex) => {
        if (boldIndex % 2 === 1) {
          return <strong key={`${index}-${boldIndex}`}>{boldPart}</strong>;
        }
        return boldPart;
      });
    });
  };

const renderParagraphs = (paragraphs: string[]) => {
  const elements: JSX.Element[] = [];
  let listItems: { text: string; indent: number }[] = [];

  const flushList = () => {
    if (listItems.length > 0) {
      elements.push(
        <ul key={`list-${elements.length}`} className="list-disc pl-5 my-4 space-y-2">
          {listItems.map((item, i) => (
            <li key={i} className={item.indent > 0 ? `ml-${item.indent * 4}` : ''}>
                <span dangerouslySetInnerHTML={{ __html: item.text.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>') }} />
            </li>
          ))}
        </ul>
      );
      listItems = [];
    }
  };

  for (const p of paragraphs) {
    const listItemMatch = p.match(/^(\s*\*)\s(.*)/);
    if (listItemMatch) {
      const indent = (listItemMatch[1].length - 1) / 2;
      listItems.push({ text: listItemMatch[2], indent });
    } else {
      flushList();
      elements.push(<p key={elements.length}>{renderTextWithLinks(p)}</p>);
    }
  }

  flushList();
  return elements;
};

